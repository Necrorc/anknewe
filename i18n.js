let _currentLang = 'ru';

function setLang(lang) {
  _currentLang = TRANSLATIONS[lang] ? lang : 'ru';
}

function getLang() {
  return _currentLang;
}

/** t('some.key', {name: 'foo'}) — берёт строку из словаря текущего языка (с fallback на русский), подставляет {var}. */
function t(key, vars) {
  const dict = TRANSLATIONS[_currentLang] || TRANSLATIONS.ru;
  let str = key in dict ? dict[key] : (key in TRANSLATIONS.ru ? TRANSLATIONS.ru[key] : key);
  if (vars) {
    for (const k in vars) str = str.split('{' + k + '}').join(vars[k]);
  }
  return str;
}

/** Проставляет переводы во все статические элементы разметки (вызывается при старте и при смене языка). */
function applyStaticTranslations() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.getAttribute('data-i18n-html'));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
  });
  document.title = t('app.fullTitle');
  const appleTitle = document.querySelector('meta[name="apple-mobile-web-app-title"]');
  if (appleTitle) appleTitle.setAttribute('content', t('app.title'));
}
